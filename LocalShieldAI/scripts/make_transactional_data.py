"""Create data/train_extra/transactional_sms.csv: extra TRAINING messages.

Why: the UCI training data is old UK/Singapore SMS. Real modern OTP, bank, delivery
and security messages look nothing like its normal messages, but share words
("account", "login", "verify", "delivery") with its spam, so the model flags them.
This file adds normal messages of those kinds (label 0) and scam messages written in
the SAME tone (label 1), so the model has to learn the real signals (links to odd
domains, pressure, asking for secrets) and not just the topic words.

IMPORTANT FOR THE REPORT: this data is TEMPLATE-GENERATED by the author. It is used
for training only, never for validation/test. Evaluate on data/eval/ files.

    python -m scripts.make_transactional_data"""
import csv
import random
from pathlib import Path

random.seed(7)
OUT = Path(__file__).resolve().parent.parent / "data" / "train_extra" / "transactional_sms.csv"

APPS = ["Paytm", "PhonePe", "Amazon", "Flipkart", "Swiggy", "Zomato", "Google", "Instagram",
        "Myntra", "Uber", "Ola", "IRCTC", "Airtel", "Jio", "Netflix", "Microsoft"]
BANKS = ["HDFC Bank", "SBI", "ICICI Bank", "Axis Bank", "Kotak Bank", "Canara Bank",
         "Bank of Baroda", "PNB", "IDFC First Bank", "Yes Bank"]
COURIERS = ["Delhivery", "Blue Dart", "India Post", "DTDC", "Ecom Express", "Amazon Logistics"]
OFFICIAL = ["amazon.in", "flipkart.com", "irctc.co.in", "swiggy.com", "sbi.co.in", "hdfcbank.com",
            "paytm.com", "myntra.com", "bluedart.com", "indiapost.gov.in", "airtel.in", "jio.com"]
FAKE = ["bit.ly/{r}", "tinyurl.com/{r}", "{b}-secure-login.xyz/verify", "{b}-kyc-update.top/x",
        "{b}-support.click/a{n}", "verify-{b}.icu/login", "{b}-refund.cfd/claim", "cutt.ly/{r}",
        "{b}-account.link/confirm", "update-{b}.sbs/{n}"]
COLLEGE = ["the college Wi-Fi network", "the campus network", "the hostel Wi-Fi", "the library network",
           "the university Wi-Fi"]


def p(x):
    return random.choice(x)


def amt():
    return p(["", "Rs."]) + f"{random.choice([49, 99, 150, 250, 499, 799, 1200, 2500, 4999, 12000])}"


def otp():
    return str(random.randint(100000, 999999)) if random.random() < 0.8 else str(random.randint(1000, 9999))


def last4():
    return f"{random.randint(1000, 9999)}"


def rnd():
    return "".join(random.choice("abcdefghijkmnpqrstuvwxyz23456789") for _ in range(random.randint(5, 7)))


def fake_link(brand):
    return "http://" + p(FAKE).format(r=rnd(), b=brand.lower().replace(" ", ""), n=random.randint(1, 999))


def official_link():
    return "https://www." + p(OFFICIAL)


# ---------------- NORMAL messages (label 0) ----------------
def ham():
    app, bank, cour = p(APPS), p(BANKS), p(COURIERS)
    fams = [
        lambda: f"{otp()} is your one time password for {app}. It is valid for 10 minutes. Do not share it with anyone.",
        lambda: f"Your verification code is {otp()}. Never share this code with anyone, including our staff.",
        lambda: f"Use {otp()} as the login code for your {app} account. This code expires in 5 minutes.",
        lambda: f"{otp()} is the OTP for your card payment of {amt()} at {app}. Do not give it to anyone.",
        lambda: f"A new sign in to your {app} account was noticed from a new device. If this was you, no action is needed. If not, change your password in the official app.",
        lambda: f"Security notice: your {app} password was changed today. If you did this, you can ignore this message.",
        lambda: f"We noticed a login to your account on a new phone. If it was you, there is nothing to do. Otherwise open the {app} app and secure your account.",
        lambda: f"Payment of {amt()} received successfully on {app}. Thank you for using our service.",
        lambda: f"Your payment of {amt()} to {app} was successful. Transaction complete. Reference {random.randint(10**9, 10**10 - 1)}.",
        lambda: f"{bank}: Rs.{random.randint(100, 50000)}.00 credited to your account ending {last4()}. Available balance updated.",
        lambda: f"{bank}: Rs.{random.randint(50, 9000)}.00 debited from account ending {last4()} for a UPI payment. If not done by you, call the number on the back of your card.",
        lambda: f"Your account balance was updated after your recent transaction. Open the official {bank} app to see your latest statement.",
        lambda: f"Your monthly statement for the account ending {last4()} is ready. You can view it in the {bank} mobile app.",
        lambda: f"Your {cour} package has reached the local delivery centre and is out for delivery today. No action is required.",
        lambda: f"Your order from {app} has been shipped and will arrive on {p(['Monday', 'Tuesday', 'Friday', 'Saturday'])}. Thank you for shopping with us.",
        lambda: f"Parcel update: your shipment is at the nearest hub and will be delivered today between 10 AM and 6 PM. Someone should be available to receive it.",
        lambda: f"Your delivery partner is nearby. Share the code {random.randint(1000, 9999)} with the delivery person only when you receive your order.",
        lambda: f"Your device is now connected to {p(COLLEGE)}. You can use the internet as usual. Contact the IT department if you face connection problems.",
        lambda: f"Welcome to {p(COLLEGE)}. Your device registration is complete. For help, visit the IT help desk in the main building.",
        lambda: f"Reminder: your appointment is tomorrow at {random.randint(9, 17)}:00. Reply C to confirm or call the clinic to reschedule.",
        lambda: f"Your recharge of {amt()} was successful. Your plan is valid for {p([28, 56, 84])} days. Thank you.",
        lambda: f"Your booking is confirmed. PNR {random.randint(10**9, 10**10 - 1)}. Have a safe journey.",
        lambda: f"Class notice: tomorrow's lecture is moved to Room {random.randint(101, 410)}. Please check the notice board for details.",
        lambda: f"Your electricity bill of {amt()} has been paid. Thank you. Your receipt is available in the app.",
        lambda: f"Your {app} subscription renews on the {random.randint(1, 28)}th. No action is needed. You can manage it in the app settings.",
        lambda: f"Your account ending {last4()} will receive your salary on the 1st. Have a good day.",
        lambda: f"Hi, this is a reminder that the library book you borrowed is due on Friday. Please return it to avoid a late fee.",
    ]
    t = p(fams)()
    if random.random() < 0.18:  # some real messages carry an official link
        t += " Details: " + official_link()
    return t


# ---------------- SCAM messages in the same tone (label 1) ----------------
def scam():
    app, bank, cour = p(APPS), p(BANKS), p(COURIERS)
    b = bank.split()[0]
    fams = [
        lambda: f"Your {bank} OTP is {otp()}. Share it with our officer now to cancel the transaction of {amt()}.",
        lambda: f"{bank} alert: unusual sign in on your account. Verify your identity immediately at {fake_link(b)} or your account will be blocked.",
        lambda: f"Security alert! Your {app} password has expired. Update it now at {fake_link(app)} to avoid suspension.",
        lambda: f"URGENT: your {bank} account is blocked. Complete KYC within 24 hours: {fake_link(b)}",
        lambda: f"Payment of {amt()} is pending on your {app} account. Pay now to avoid penalty: {fake_link(app)}",
        lambda: f"Refund of {amt()} is ready for you. Enter your card number and OTP to receive it: {fake_link(b)}",
        lambda: f"Dear customer, your {bank} account balance is low. Click {fake_link(b)} and share your PIN to keep the account active.",
        lambda: f"Your {cour} parcel could not be delivered. Pay a small fee of Rs.{random.choice([19, 29, 49])} to reschedule: {fake_link(cour)}",
        lambda: f"Your package is held at customs. Pay the release charge today at {fake_link('customs')} or it will be returned.",
        lambda: f"Congratulations! You have won {amt()} in the {app} lucky draw. Claim your prize now: {fake_link(app)}",
        lambda: f"Your {app} KYC is incomplete and your wallet will be suspended tonight. Update details at {fake_link(app)}",
        lambda: f"Your electricity connection will be cut tonight. Pay the pending bill immediately: {fake_link('billpay')}",
        lambda: f"Pre-approved loan of Rs.{random.choice([50000, 200000, 500000])} for you. No documents needed. Apply now: {fake_link('loan')}",
        lambda: f"Work from home job: earn Rs.{random.choice([3000, 5000, 8000])} per day. Message your bank details on WhatsApp now.",
        lambda: f"Your device Wi-Fi access will be disabled. Log in again with your college password at {fake_link('college')} to keep it.",
        lambda: f"A login to your account was detected. Confirm your password and OTP here to secure it: {fake_link(app)}",
        lambda: f"Your {bank} debit card has been blocked. Call 9{random.randint(10**8, 10**9 - 1)} now and give your card number and PIN to unblock.",
        lambda: f"Your SIM will be deactivated in 2 hours. Complete verification now: {fake_link('sim')}",
    ]
    return p(fams)()


def main():
    rows, seen = [], set()
    for label, fn, n in ((0, ham, 520), (1, scam, 320)):
        tries = 0
        count = 0
        while count < n and tries < n * 30:
            tries += 1
            t = fn()
            if t not in seen:
                seen.add(t)
                rows.append((label, t))
                count += 1
    random.shuffle(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["label", "text"])
        w.writerows(rows)
    print(f"Wrote {OUT}: {sum(1 for r in rows if r[0] == 0)} normal, {sum(1 for r in rows if r[0] == 1)} scam")


if __name__ == "__main__":
    main()